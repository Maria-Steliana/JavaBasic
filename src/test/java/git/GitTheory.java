package git;

public class GitTheory {
    // Despre Git
    //===================
    // - Git este un sistem distribuit de control al versiunilor;
    // - Este folosit pentru a urmari si gestiona toate modificarile facute in fisierele unui proiect;
    // - Este folosit in special pentru codul sursa, dar poate fi folosit pentru orice fisier;
    // - Salveaza istoricul modificarilor din proiect, permite revenirea la orice versiune anterioara a unui proiect
    // - Permite lucrul individual, cat si colaborativ;


    // Despre GitHub
    //===================
    // - Este o platforma online care gazduieste proiecte ce folosesc GIT;
    // - Permite colaborarea cu alti dezvoltatori, dar indiferent unde se afla ei.

    // Git = unealta locala; GitHub = platforma online

    // Termeni de baza in Git
    //===================
    // Repository(Repo) = proiectul "tau" gestionat cu Git;
    // Commit = salvarea unui set de modificari ca un mesaj explicativ;
    // Branch = o ramura pe care poti dezvolta functionalitati fara a afecta codul principal;
    // Merge = combinarea modificarilor dintr-o ramura in alta;
    // Push = trimiterea modificarilor locale catre un repository remote (Git Local -> GitHub Remote);
    // Pull = descarcarea ultimelor modificari de pe remote pe local (GitHub Remote -> Git Local).
}

